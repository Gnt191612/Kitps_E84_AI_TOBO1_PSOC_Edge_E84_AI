#define MODEL_INPUT_SIZE        (MODEL_INPUT_WIDTH * MODEL_INPUT_HEIGHT)
/* Input quantization from ml-coretools q_param.txt: scale 1.0, zero_point -128 */
#define INPUT_ZERO_POINT        (-128)

